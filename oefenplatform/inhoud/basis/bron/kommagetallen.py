"""🧱 Basis — Kommagetallen vergelijken, optellen en aftrekken.

Kim merkte op 23 september 2026 dat kinderen dachten dat 0,7 kleiner was dan
0,65, "vermits dat ze de waarde als 7 en 65 bezagen". Daarom komt die valkuil
hier telkens terug: in sleepoefeningen op een getallenlijn, in het honderdveld,
en in de uitleg (maak ze eerst even lang: 0,70 en 0,65).

Bij optellen en aftrekken zijn de foute opties de fouten die je krijgt als je
de komma's niet onder elkaar zet.

Deel 1: vergelijken met evenveel of één cijfer verschil, eenvoudig optellen en
aftrekken.
Deel 2: getallen van verschillende lengte, breuken ertussen, geld en meten.
"""

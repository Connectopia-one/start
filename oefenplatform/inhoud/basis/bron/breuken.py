# -*- coding: utf-8 -*-
"""🧱 Basis — Breuken, kommagetallen en gehele getallen.

Deel 1: breuken met noemer 10 of 100, de breuken die je vanbuiten kent, en
breuken die een geheel getal zijn.
Deel 2: noemer eerst 10 of 100 maken, terug van kommagetal naar breuk,
breuken groter dan één en vergelijken.
"""
from fractions import Fraction as F
from reken import g, getal, mk, invul, won, enige, stijgend, WOORD

DEEL1 = [
    mk("Je eet de helft van een pizza. Welk kommagetal hoort bij een half?", [r"\(0{,}5\)", r"\(0{,}2\)", r"\(1{,}2\)"],
       r"Een half is \(\tfrac{1}{2}\), en \(1 : 2 = 0{,}5\).",
       F(1, 2)),
    mk(r"Welk kommagetal is hetzelfde als \(\tfrac{7}{10}\)?", [r"\(0{,}7\)", r"\(7{,}10\)", r"\(0{,}07\)"],
       r"Zeven tienden: \(7 : 10 = 0{,}7\). De \(7\) komt op de plaats van de tienden, net achter de komma.",
       F(7, 10)),
    mk(r"Welk kommagetal is hetzelfde als \(\tfrac{23}{100}\)?", [r"\(0{,}23\)", r"\(2{,}3\)", r"\(23{,}100\)"],
       r"\(23 : 100\): de komma springt twee plaatsen naar links. \(0{,}23\).",
       F(23, 100)),
    invul(r"Schrijf \(\tfrac{9}{10}\) als kommagetal.", "0,9",
          r"\(9 : 10 = 0{,}9\). Negen tienden.",
          F(9, 10)),
    mk(r"Welk kommagetal is \(\tfrac{1}{4}\)?", [r"\(0{,}25\)", r"\(0{,}4\)", r"\(1{,}4\)"],
       r"\(\tfrac{1}{4} = \tfrac{25}{100} = 0{,}25\). Denk aan een kwart euro: \(25\) cent.",
       F(1, 4)),
    mk(r"Welk kommagetal is \(\tfrac{3}{4}\)?", [r"\(0{,}75\)", r"\(0{,}34\)", r"\(3{,}4\)"],
       r"\(\tfrac{3}{4} = \tfrac{75}{100} = 0{,}75\). Drie kwart euro is \(75\) cent.",
       F(3, 4)),
    won(r"\(\tfrac{1}{2} = 0{,}5\)", True,
        r"Waar. \(1 : 2 = 0{,}5\).",
        F(1, 2) == g("0,5")),
    mk(r"Welke breuk is \(0{,}3\)?", [r"\(\tfrac{3}{10}\)", r"\(\tfrac{3}{100}\)", r"\(\tfrac{1}{3}\)"],
       r"Eén cijfer na de komma, dus de noemer is \(10\): \(0{,}3 = \tfrac{3}{10}\). Let op: \(\tfrac{1}{3}\) is geen \(0{,}3\).",
       g("0,3")),
    mk(r"Welke breuk is \(0{,}07\)?", [r"\(\tfrac{7}{100}\)", r"\(\tfrac{7}{10}\)", r"\(\tfrac{7}{1000}\)"],
       r"Twee cijfers na de komma, dus de noemer is \(100\): \(0{,}07 = \tfrac{7}{100}\).",
       g("0,07")),
    invul(r"\(0{,}5 = \ldots\)/\(10\). Welk getal hoort op de puntjes?", "5",
          r"Eén cijfer na de komma, dus over \(10\): \(0{,}5 = \tfrac{5}{10}\).",
          g("0,5") * 10),
    mk(r"Hoeveel is \(\tfrac{8}{4}\)?", [r"\(2\)", r"\(4\)", r"\(32\)"],
       r"De breukstreep is gedeeld door: \(8 : 4 = 2\).",
       F(8, 4)),
    mk(r"Hoeveel is \(\tfrac{12}{3}\)?", [r"\(4\)", r"\(9\)", r"\(36\)"],
       r"\(12 : 3 = 4\).",
       F(12, 3)),
    invul(r"Hoeveel is \(\tfrac{20}{4}\)?", "5",
          r"\(20 : 4 = 5\). De deling gaat op, dus het is een geheel getal.",
          F(20, 4)),
    won(r"\(\tfrac{5}{5} = 1\)", True,
        "Waar. Je neemt alle vijf de stukken: dat is het hele geheel.",
        F(5, 5) == 1),
    mk("Welke breuk is een geheel getal?", [r"\(\tfrac{6}{3}\)", r"\(\tfrac{5}{3}\)", r"\(\tfrac{7}{3}\)"],
       r"\(6\) staat in de tafel van \(3\), dus \(6 : 3 = 2\) gaat op. Bij \(5\) en \(7\) blijft er iets over.",
       enige(["6/3", "5/3", "7/3"], lambda b: getal(b).denominator == 1)),
    mk(r"Wat betekent de breukstreep in \(\tfrac{3}{4}\)?", ["Gedeeld door", "Maal", "Min"],
       r"De breukstreep betekent gedeeld door: \(\tfrac{3}{4} = 3 : 4\).",
       WOORD),
    mk(r"Welk kommagetal is \(\tfrac{1}{5}\)?", [r"\(0{,}2\)", r"\(0{,}5\)", r"\(1{,}5\)"],
       r"\(\tfrac{1}{5} = \tfrac{2}{10} = 0{,}2\). Maak de noemer \(10\) door teller en noemer maal \(2\) te doen.",
       F(1, 5)),
    won(r"\(0{,}4\) is hetzelfde als \(\tfrac{1}{4}\).", False,
        r"Niet waar. \(\tfrac{1}{4} = 0{,}25\). \(0{,}4\) is \(\tfrac{4}{10}\), en dat is \(\tfrac{2}{5}\).",
        g("0,4") == F(1, 4)),
    mk(r"Schrijf \(\tfrac{3}{2}\) als kommagetal.", [r"\(1{,}5\)", r"\(3{,}2\)", r"\(0{,}32\)"],
       r"\(3 : 2 = 1{,}5\). Drie halven is anderhalf.",
       F(3, 2)),
    invul(r"Schrijf \(\tfrac{45}{100}\) als kommagetal.", "0,45",
          r"\(45 : 100\): twee sprongen naar links. \(0{,}45\).",
          F(45, 100)),
]


# -*- coding: utf-8 -*-
"""🧱 Basis — Breuken, kommagetallen en gehele getallen.

Deel 1: breuken met noemer 10 of 100, de breuken die je vanbuiten kent, en
breuken die een geheel getal zijn.
Deel 2: noemer eerst 10 of 100 maken, terug van kommagetal naar breuk,
breuken groter dan één en vergelijken.
"""
from fractions import Fraction as F
from reken import g, getal, mk, invul, won, enige, stijgend, WOORD

DEEL1 = [
    mk("Je eet de helft van een pizza. Welk kommagetal hoort bij een half?", ["0,5", "0,2", "1,2"],
       "Een half is 1/2, en 1 : 2 = 0,5.",
       F(1, 2)),
    mk("Welk kommagetal is hetzelfde als 7/10?", ["0,7", "7,10", "0,07"],
       "Zeven tienden: 7 : 10 = 0,7. De 7 komt op de plaats van de tienden, net achter de komma.",
       F(7, 10)),
    mk("Welk kommagetal is hetzelfde als 23/100?", ["0,23", "2,3", "23,100"],
       "23 : 100: de komma springt twee plaatsen naar links. 0,23.",
       F(23, 100)),
    invul("Schrijf 9/10 als kommagetal.", "0,9",
          "9 : 10 = 0,9. Negen tienden.",
          F(9, 10)),
    mk("Welk kommagetal is 1/4?", ["0,25", "0,4", "1,4"],
       "1/4 = 25/100 = 0,25. Denk aan een kwart euro: 25 cent.",
       F(1, 4)),
    mk("Welk kommagetal is 3/4?", ["0,75", "0,34", "3,4"],
       "3/4 = 75/100 = 0,75. Drie kwart euro is 75 cent.",
       F(3, 4)),
    won("1/2 = 0,5", True,
        "Waar. 1 : 2 = 0,5.",
        F(1, 2) == g("0,5")),
    mk("Welke breuk is 0,3?", ["3/10", "3/100", "1/3"],
       "Eén cijfer na de komma, dus de noemer is 10: 0,3 = 3/10. Let op: 1/3 is geen 0,3.",
       g("0,3")),
    mk("Welke breuk is 0,07?", ["7/100", "7/10", "7/1000"],
       "Twee cijfers na de komma, dus de noemer is 100: 0,07 = 7/100.",
       g("0,07")),
    invul("0,5 = …/10. Welk getal hoort op de puntjes?", "5",
          "Eén cijfer na de komma, dus over 10: 0,5 = 5/10.",
          g("0,5") * 10),
    mk("Hoeveel is 8/4?", ["2", "4", "32"],
       "De breukstreep is gedeeld door: 8 : 4 = 2.",
       F(8, 4)),
    mk("Hoeveel is 12/3?", ["4", "9", "36"],
       "12 : 3 = 4.",
       F(12, 3)),
    invul("Hoeveel is 20/4?", "5",
          "20 : 4 = 5. De deling gaat op, dus het is een geheel getal.",
          F(20, 4)),
    won("5/5 = 1", True,
        "Waar. Je neemt alle vijf de stukken: dat is het hele geheel.",
        F(5, 5) == 1),
    mk("Welke breuk is een geheel getal?", ["6/3", "5/3", "7/3"],
       "6 staat in de tafel van 3, dus 6 : 3 = 2 gaat op. Bij 5 en 7 blijft er iets over.",
       enige(["6/3", "5/3", "7/3"], lambda b: getal(b).denominator == 1)),
    mk("Wat betekent de breukstreep in 3/4?", ["Gedeeld door", "Maal", "Min"],
       "De breukstreep betekent gedeeld door: 3/4 = 3 : 4.",
       WOORD),
    mk("Welk kommagetal is 1/5?", ["0,2", "0,5", "1,5"],
       "1/5 = 2/10 = 0,2. Maak de noemer 10 door teller en noemer maal 2 te doen.",
       F(1, 5)),
    won("0,4 is hetzelfde als 1/4.", False,
        "Niet waar. 1/4 = 0,25. 0,4 is 4/10, en dat is 2/5.",
        g("0,4") == F(1, 4)),
    mk("Schrijf 3/2 als kommagetal.", ["1,5", "3,2", "0,32"],
       "3 : 2 = 1,5. Drie halven is anderhalf.",
       F(3, 2)),
    invul("Schrijf 45/100 als kommagetal.", "0,45",
          "45 : 100: twee sprongen naar links. 0,45.",
          F(45, 100)),
]

DEEL2 = [
    mk("Welk kommagetal is 2/5?", ["0,4", "0,25", "2,5"],
       "Maak de noemer 10: 2/5 = 4/10 = 0,4.",
       F(2, 5)),
    mk("Welk kommagetal is 3/5?", ["0,6", "0,35", "3,5"],
       "Maak de noemer 10: 3/5 = 6/10 = 0,6.",
       F(3, 5)),
    invul("Schrijf 3/4 als kommagetal.", "0,75",
          "Maak de noemer 100: 3/4 = 75/100 = 0,75.",
          F(3, 4)),
    mk("Welk kommagetal is 7/1000?", ["0,007", "0,07", "0,7"],
       "7 : 1000: drie sprongen naar links. 0,007.",
       F(7, 1000)),
    mk("Schrijf 0,25 als breuk, zo eenvoudig mogelijk.", ["1/4", "25/10", "2/5"],
       "0,25 = 25/100. Deel teller en noemer door 25: 1/4.",
       g("0,25")),
    mk("Schrijf 0,6 als breuk, zo eenvoudig mogelijk.", ["3/5", "6/100", "1/6"],
       "0,6 = 6/10. Deel teller en noemer door 2: 3/5.",
       g("0,6")),
    mk("Welke breuk is 0,125?", ["125/1000", "125/100", "12/5"],
       "Drie cijfers na de komma, dus de noemer is 1000: 125/1000. Vereenvoudigd is dat 1/8.",
       g("0,125")),
    invul("0,75 = …/100. Welk getal hoort op de puntjes?", "75",
          "Twee cijfers na de komma, dus over 100: 75/100.",
          g("0,75") * 100),
    mk("Schrijf 7/2 als kommagetal.", ["3,5", "7,2", "2,7"],
       "7 : 2 = 3 rest 1. Dat is 3 en een half: 3,5.",
       F(7, 2)),
    mk("Schrijf 9/4 als gemengd getal.", ["2 1/4", "9 1/4", "3 1/4"],
       "9 : 4 = 2 rest 1. Dus 2 gehelen en nog 1/4: 2 1/4.",
       F(9, 4)),
    mk("Schrijf 9/4 als kommagetal.", ["2,25", "9,4", "0,94"],
       "9/4 = 2 1/4, en 1/4 = 0,25. Samen 2,25.",
       F(9, 4)),
    won("15/3 is een geheel getal.", True,
        "Waar. 15 : 3 = 5, en die deling gaat op.",
        F(15, 3).denominator == 1),
    won("14/4 is een geheel getal.", False,
        "Niet waar. 14 : 4 = 3 rest 2, dus 14/4 = 3,5.",
        F(14, 4).denominator == 1),
    mk("Welke breuk is gelijk aan 3?", ["12/4", "4/12", "3/9"],
       "12 : 4 = 3. 4/12 en 3/9 zijn kleiner dan één.",
       3),
    mk("Welk getal is het grootst?", ["0,6", "1/2", "0,55"],
       "Maak er kommagetallen van: 1/2 = 0,5. Dan vergelijk je 0,60, 0,50 en 0,55: 0,6 wint.",
       max(["0,6", "1/2", "0,55"], key=getal)),
    mk("Welk getal is het kleinst?", ["1/4", "0,3", "0,5"],
       "1/4 = 0,25, en dat is kleiner dan 0,3 en 0,5.",
       min(["1/4", "0,3", "0,5"], key=getal)),
    invul("1,5 = …/2. Welk getal hoort op de puntjes?", "3",
          "1,5 is anderhalf, en dat zijn drie halven: 3/2.",
          g("1,5") * 2),
    mk("Lisa eet 3/4 van een reep chocolade van 100 g. Hoeveel gram eet ze?", ["75 g", "34 g", "25 g"],
       "1/4 van 100 g is 25 g. Drie keer zoveel is 75 g.",
       F(3, 4) * 100),
    mk("Welke rij staat van klein naar groot?", ["0,2 · 1/2 · 0,7", "1/2 · 0,2 · 0,7", "0,7 · 1/2 · 0,2"],
       "1/2 = 0,5. Dan is de volgorde 0,2, 0,5, 0,7.",
       enige(["0,2 · 1/2 · 0,7", "1/2 · 0,2 · 0,7", "0,7 · 1/2 · 0,2"], stijgend)),
    won("0,5 en 5/10 en 1/2 zijn drie namen voor hetzelfde getal.", True,
        "Waar. Ze staan alle drie op dezelfde plek op de getallenlijn, precies in het midden tussen 0 en 1.",
        g("0,5") == F(5, 10) == F(1, 2)),
]
